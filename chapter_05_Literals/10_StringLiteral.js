let single = 'Hello, World!';
let double = "Hello, World!";
let backticks = `Hello, World!`;

console.log('Single quotes ->', single);
console.log('Double quotes ->', double);
console.log('Backticks ->', backticks);

console.log('Type of single ->', typeof single);
console.log('Type of double ->', typeof double);
console.log('Type of backticks ->', typeof backticks);  