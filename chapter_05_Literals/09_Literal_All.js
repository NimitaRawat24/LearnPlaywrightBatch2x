// Integer literals
let decimalInteger = 42;
let negativeInteger = -100;
let zero = 0;

// Floating-point literals
let floatValue = 3.14;
let negativeFloat = -0.5;

// Exponential (scientific) notation
let largeNumber = 1.23e6;      // 1.23 × 10^6
let smallNumber = 5.67e-4;     // 5.67 × 10^-4

// Binary, octal, and hexadecimal literals
let binaryValue = 0b101010;    // binary for 42
let octalValue = 0o52;         // octal for 42
let hexValue = 0x2A;           // hexadecimal for 42

// BigInt literal (integer values larger than Number.MAX_SAFE_INTEGER)
let bigIntValue = 123456789012345678901234567890n;

// Special numeric values
let infinityValue = Infinity;
let negativeInfinity = -Infinity;
let notANumber = NaN;

// Numeric separator for readability
let readableNumber = 1_000_000;
let price = 12_345.67_89;